def clean_dialog(s):
    # Aplica todas as substituições do dicionário
    for eng, pt in DICTIONARY:
        if eng in s:
            s = s.replace(eng, pt)
    # Palavras isoladas seguras
    if s == "Yes": s = "Sim"
    elif s == "No": s = "Nao"
    s = re.sub(r'\bYes\b', 'Sim', s)
    s = re.sub(r'\bNo\b', 'Nao', s)
    return s

def main():
    print("Traduzindo mapas e interiores em lang/pt_br/maps_dialogs.json...")
    with open("lang/pt_br/maps_dialogs.json", "r", encoding="utf-8") as f:
        data = json.load(f)

    count_translated = 0
    for map_key, map_info in data.items():
        dialogs = map_info.get("dialogs", [])
        new_dialogs = []
        for d in dialogs:
            translated = clean_dialog(d)
            if translated != d:
                count_translated += 1
            new_dialogs.append(translated)
        map_info["dialogs"] = new_dialogs

    with open("lang/pt_br/maps_dialogs.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Sucesso! {count_translated} frases traduzidas em lang/pt_br/maps_dialogs.json.")

if __name__ == "__main__":
    main()
